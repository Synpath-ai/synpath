class TestSigningVectors:
    signer = sig.WalletSigner(KEY)

    def test_signer_address(self):
        assert self.signer.address == ADDRESS

    @pytest.mark.parametrize("vector", VECTORS["orders"], ids=lambda v: f"type{v['signature_type']}-{'negrisk' if v['neg_risk'] else 'std'}-{v['side']}")
    def test_order_signature_and_hash(self, vector):
        order = sig.build_order(
            maker=vector["maker"], signer=vector["signer"], token_id=vector["token_id"],
            maker_amount=vector["maker_amount"], taker_amount=vector["taker_amount"], side=vector["side"],
            signature_type=vector["signature_type"], timestamp_ms=vector["timestamp"], salt=vector["salt"],
            expiration=int(vector["expiration"]), builder=vector["builder"],
        )
        assert sig.sign_order(self.signer, order, neg_risk=vector["neg_risk"]) == vector["signature"]
        assert sig.order_hash(order, neg_risk=vector["neg_risk"]) == vector["hash"]

    def test_every_limit_amount_case(self):
        mismatched = [
            case for case in VECTORS["amounts"]
            if sig.limit_amounts(case["side"], D(case["price"]), D(case["size"]), D(case["tick"])) != (case["maker"], case["taker"])
        ]
        assert len(VECTORS["amounts"]) == 1140
        assert mismatched == []

    @pytest.mark.parametrize("vector", VECTORS["l1"])
    def test_l1_signature(self, vector):
        headers = sig.l1_headers(self.signer, vector["timestamp"], vector["nonce"])
        assert headers["POLY_SIGNATURE"] == vector["signature"]
        assert headers["POLY_ADDRESS"] == ADDRESS and headers["POLY_NONCE"] == str(vector["nonce"])

    @pytest.mark.parametrize("vector", VECTORS["hmac"])
    def test_l2_hmac(self, vector):
        assert sig.l2_signature(vector["secret"], vector["timestamp"], vector["method"], vector["path"], vector["body"]) == vector["signature"]

    def test_the_documented_buy_example(self):
        # The venue's own worked example: BUY 10 at 0.52 -> 5200000 / 10000000.
        assert sig.limit_amounts("BUY", D("0.52"), D("10"), D("0.01")) == (5_200_000, 10_000_000)
        assert sig.limit_amounts("SELL", D("0.52"), D("10"), D("0.01")) == (10_000_000, 5_200_000)

    def test_unknown_tick_is_refused(self):
        with pytest.raises(InvalidOrder, match="precision"):
            sig.limit_amounts("BUY", D("0.5"), D("10"), D("0.02"))


class TestWalletCalls:
    def test_selectors_are_the_conditional_tokens_ones(self):
        # Published selectors of ERC-20, ERC-1155 and the Gnosis CTF.
        assert sig.approve_calldata(sig.EXCHANGE).startswith("0x095ea7b3")
        assert sig.set_approval_for_all_calldata(sig.EXCHANGE).startswith("0xa22cb465")
        assert sig.split_calldata(CONDITION, 1).startswith("0x72ce4275")
        assert sig.merge_calldata(CONDITION, 1).startswith("0x9e7212ad")
        assert sig.redeem_calldata(CONDITION).startswith("0x01b7037c")

    def test_split_encodes_pusd_condition_partition_and_amount(self):
        from eth_abi import decode
        data = bytes.fromhex(sig.split_calldata(CONDITION, 5_000_000)[10:])
        collateral, parent, condition, partition, amount = decode(["address", "bytes32", "bytes32", "uint256[]", "uint256"], data)
        assert collateral.lower() == sig.PUSD.lower() and parent == b"\x00" * 32
        assert "0x" + condition.hex() == CONDITION and list(partition) == [1, 2] and amount == 5_000_000

    def test_bad_condition_id(self):
        with pytest.raises(InvalidOrder, match="condition id"):
            sig.redeem_calldata("0x1234")

    def test_approval_calls_cover_each_spender_for_both_tokens(self):
        calls = sig.trading_approval_calls([sig.EXCHANGE, sig.NEG_RISK_EXCHANGE])
        assert [c["target"] for c in calls] == [sig.PUSD, sig.PUSD, sig.CONDITIONAL_TOKENS, sig.CONDITIONAL_TOKENS]
        assert sig.NEG_RISK_EXCHANGE[2:].lower() in calls[1]["data"].lower()
        assert len(sig.trading_approval_calls()) == 8

    def test_wallet_batch_signature_recovers_to_the_signer(self):
        signer = sig.WalletSigner(KEY)
        calls = sig.trading_approval_calls([sig.EXCHANGE])
        typed = sig.wallet_batch_typed_data(WALLET, 7, 1_800_000_000, calls)
        signature = signer.sign_typed_data(typed)
        assert EthAccount.recover_message(encode_typed_data(full_message=typed), signature=signature) == ADDRESS
        assert typed["domain"]["verifyingContract"] == WALLET and typed["domain"]["name"] == "DepositWallet"

    def test_deposit_wallet_wrap_layout(self):
        signer = sig.WalletSigner(KEY)
        order = sig.build_order(maker=WALLET, signer=WALLET, token_id=TOKEN, maker_amount=1, taker_amount=2,
                                side="BUY", signature_type=3, timestamp_ms=1, salt=1)
        raw = bytes.fromhex(sig.sign_order(signer, order, neg_risk=False)[2:])
        type_bytes = sig.ORDER_TYPE.encode()
        assert int.from_bytes(raw[-2:], "big") == len(type_bytes)
        assert raw[-2 - len(type_bytes):-2] == type_bytes
        assert len(raw) == 65 + 32 + 32 + len(type_bytes) + 2


